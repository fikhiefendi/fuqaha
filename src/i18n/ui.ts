export const LOCALES = ['tr', 'en', 'ar'] as const;
export type Lang = (typeof LOCALES)[number];
export const DEFAULT_LANG: Lang = 'tr';

export const LANG_META: Record<Lang, { name: string; short: string; dir: 'ltr' | 'rtl'; intl: string }> = {
  tr: { name: 'Türkçe', short: 'TR', dir: 'ltr', intl: 'tr-TR' },
  en: { name: 'English', short: 'EN', dir: 'ltr', intl: 'en-GB' },
  ar: { name: 'العربية', short: 'ع', dir: 'rtl', intl: 'ar' },
};

// A value that may exist in several languages.
export type Localized<T = string> = Partial<Record<Lang, T>>;

/** Picks the requested language, falling back to Turkish, then English, then Arabic. */
export function pick<T>(value: Localized<T> | undefined, lang: Lang): T | undefined {
  if (!value) return undefined;
  return value[lang] ?? value.tr ?? value.en ?? value.ar;
}

